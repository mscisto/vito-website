// Run after editing a standalone HTML page to refresh seamless navigation content.
const fs = require('node:fs');
const path = require('node:path');

function decodeEntities(text) {
  const entities = { amp: '&', quot: '"', apos: "'", lt: '<', gt: '>' };
  return text.replace(/&(amp|quot|apos|lt|gt);/g, (_, name) => entities[name]);
}

const pages = {};
for (const filename of fs.readdirSync(__dirname).filter(name => name.endsWith('.html')).sort()) {
  const html = fs.readFileSync(path.join(__dirname, filename), 'utf8');
  function find(expression) {
    const match = html.match(expression);
    if (!match) throw new Error(`Missing page content in ${filename}`);
    return match[1];
  }
  pages[filename] = {
    title: decodeEntities(find(/<title>([\s\S]*?)<\/title>/)),
    description: decodeEntities(find(/<meta name="description" content="([^"]*)"/)),
    header: find(/(<header\b[\s\S]*?<\/header>)/),
    main: find(/(<main\b[\s\S]*?<\/main>)/),
    footer: find(/(<footer\b[\s\S]*?<\/footer>)/),
  };
}

const output = '// Page fragments for seamless local and HTTP navigation.\n'
  + '// Generated by node sync-pages.cjs.\n'
  + `window.portfolioPages = ${JSON.stringify(pages, null, 2)};\n`;
fs.writeFileSync(path.join(__dirname, 'page-data.js'), output);
console.log(`Updated navigation content for ${Object.keys(pages).length} pages.`);
